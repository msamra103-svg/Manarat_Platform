#!/usr/bin/env node
/* عدّاء قطر — packs tools/makehuman/build (boy.json + PNG textures) into js/boy-data.js.
 * Compact binary (float32 positions, unorm16 UVs, uint8 skin indices/weights, uint16 indices) as base64,
 * textures as WebP data URIs, so the game runs from file:// with no network and no loader.
 * Usage: node tools/pack-boy.cjs [buildDir] [outFile]
 */
'use strict';
const fs = require('fs'), path = require('path');
let sharp; try { sharp = require('sharp'); } catch (_) { sharp = require('/opt/npm-tools/node_modules/sharp'); }
const dir = process.argv[2] || path.join(__dirname, 'makehuman/build');
const out = process.argv[3] || path.join(__dirname, '../js/boy-data.js');
const data = JSON.parse(fs.readFileSync(path.join(dir, 'boy.json'), 'utf8'));
const chunks = []; let offset = 0;
function push(typed) { const b = Buffer.from(typed.buffer, typed.byteOffset, typed.byteLength); const pad = (4 - (offset % 4)) % 4; if (pad) { chunks.push(Buffer.alloc(pad)); offset += pad; } const at = offset; chunks.push(b); offset += b.length; return [at, typed.length]; }
const meshes = {};
for (const [name, m] of Object.entries(data.meshes)) {
  const n = m.pos.length;
  const pos = new Float32Array(n * 3), nrm = new Int8Array(n * 3), uv = new Uint16Array(n * 2), si = new Uint8Array(n * 4), sw = new Uint8Array(n * 4);
  m.pos.forEach((p, i) => pos.set(p, i * 3));
  if (m.nrm) m.nrm.forEach((v, i) => nrm.set(v.map(x => Math.max(-127, Math.min(127, Math.round(x * 127)))), i * 3));
  m.uv.forEach((u, i) => { uv[i * 2] = Math.round(Math.min(1, Math.max(0, u[0])) * 65535); uv[i * 2 + 1] = Math.round(Math.min(1, Math.max(0, u[1])) * 65535); });
  m.skinIndex.forEach((s, i) => si.set(s, i * 4));
  m.skinWeight.forEach((w, i) => { const q = w.map(x => Math.round(x * 255)); const d = 255 - q.reduce((a, b) => a + b, 0); q[0] += d; sw.set(q, i * 4); });
  if (n > 65535) throw new Error('mesh too large for uint16 index: ' + name);
  const idx = new Uint16Array(m.index);
  meshes[name] = { count: n, pos: push(pos), nrm: m.nrm ? push(nrm) : null, uv: push(uv), si: push(si), sw: push(sw), index: push(idx) };
}
(async () => {
  const tex = {};
  const sizes = { skin: 1024, thobe: 1024, sirwal: 512, eyes: 256 };
  for (const name of Object.keys(sizes)) {
    const buf = await sharp(path.join(dir, name + '.png')).resize(sizes[name], sizes[name]).webp({ quality: name === 'skin' ? 90 : 86, alphaQuality: 100 }).toBuffer();
    tex[name] = 'data:image/webp;base64,' + buf.toString('base64');
  }
  const meta = { height: data.height, hem: data.hem, feet: data.feet, cap: data.cap, lm: data.lm, bones: data.bones, meshes, source: data.source };
  const bin = Buffer.concat(chunks).toString('base64');
  const js = `/* عدّاء قطر — packed boy model (generated by tools/pack-boy.cjs; do not edit).\n * Mesh data derived from MakeHuman 1.x CC0 assets — see docs/LICENCES.md. */\n(function(root){root.QR_BOY_DATA=${JSON.stringify(meta)};root.QR_BOY_BIN=${JSON.stringify(bin)};root.QR_BOY_TEX=${JSON.stringify(tex)};})(typeof window!=='undefined'?window:globalThis);\n`;
  fs.writeFileSync(out, js);
  console.log('wrote', out, (js.length / 1024 / 1024).toFixed(2) + ' MB', Object.fromEntries(Object.entries(meshes).map(([k, v]) => [k, v.count])));
})();
