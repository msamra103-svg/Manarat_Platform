#!/usr/bin/env node
/* عدّاء قطر — packs the generated photo-like PBR maps (tools/textures/build/*.webp, from build_env.py) into
 * js/tex-data.js as data URIs, so the world textures load offline from file:// with no network.
 * Usage: node tools/pack-tex.cjs [buildDir] [outFile]
 */
'use strict';
const fs = require('fs'), path = require('path');
const dir = process.argv[2] || path.join(__dirname, 'textures/build');
const out = process.argv[3] || path.join(__dirname, '../js/tex-data.js');
const files = fs.readdirSync(dir).filter(f => f.endsWith('.webp')).sort();
let total = 0; const lines = [];
for (const f of files) { const b = fs.readFileSync(path.join(dir, f)); total += b.length; lines.push(`  ${JSON.stringify(f.replace('.webp', ''))}: "data:image/webp;base64,${b.toString('base64')}"`); }
fs.writeFileSync(out, '/* generated by tools/pack-tex.cjs from tools/textures/build_env.py — original procedural PBR maps */\nwindow.QR_TEX_DATA = {\n' + lines.join(',\n') + '\n};\n');
console.log('packed', files.length, 'maps,', (total / 1024).toFixed(0), 'KB →', out, (fs.statSync(out).size / 1024).toFixed(0), 'KB');
