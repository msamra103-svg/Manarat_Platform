#!/usr/bin/env python3
"""Generates the tileable ocean normal map for صيد الأسماك V24.1 (original, deterministic).
Height field = inverse FFT of a Phillips wind-wave spectrum (light Gulf breeze) with a capillary tail; the normal
map stores the surface slopes. Usage: python3 gen_water_normals.py <out.png>"""
import sys, numpy as np
from PIL import Image
N, L = 512, 12.0                       # 512² texels covering a 12 m tile
rng = np.random.default_rng(1945)
k = np.fft.fftfreq(N, d=L / N) * 2 * np.pi
kx, ky = np.meshgrid(k, k); kk = np.hypot(kx, ky); kk[0, 0] = 1e-6
wind = np.array([0.9, 0.42]); wind /= np.linalg.norm(wind); V = 6.5; g = 9.81; Lw = V * V / g
ph = np.exp(-1 / (kk * Lw) ** 2) / kk ** 4 * (np.abs(kx * wind[0] + ky * wind[1]) / kk) ** 2.5
ph *= np.exp(-(kk * 0.07) ** 2)          # damp sub-centimetre waves
ph += 1.5e-6 * np.exp(-((kk - 14) / 8) ** 2) / kk ** 2   # capillary ripples, all directions
ph[0, 0] = 0
h0 = (rng.normal(size=(N, N)) + 1j * rng.normal(size=(N, N))) * np.sqrt(ph / 2)
h = np.real(np.fft.ifft2(h0)) * N * N
dx = np.real(np.fft.ifft2(1j * kx * h0)) * N * N; dy = np.real(np.fft.ifft2(1j * ky * h0)) * N * N
s = 0.55 / np.percentile(np.hypot(dx, dy), 99)
n = np.stack([-dx * s, -dy * s, np.ones_like(dx)], -1); n /= np.linalg.norm(n, axis=-1, keepdims=True)
img = ((n * 0.5 + 0.5) * 255).astype(np.uint8)
Image.fromarray(img, 'RGB').save(sys.argv[1], optimize=True)
print('water normal map', sys.argv[1], img.shape)
# the same PNG as a data-URI script so file:// offline pages can upload it to WebGL without a cross-origin taint
import base64, os
js = os.path.splitext(sys.argv[1])[0] + '.js'
with open(sys.argv[1], 'rb') as f: b64 = base64.b64encode(f.read()).decode()
with open(js, 'w') as f: f.write('/* صيد الأسماك — ocean normal map (original, generated by tools/gen_water_normals.py) */\nwindow.FISHING_WATER_NORMALS = "data:image/png;base64,' + b64 + '";\n')
print('wrote', js)
