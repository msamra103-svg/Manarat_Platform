'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const root=path.join(__dirname,'..');
const get=p=>fs.readFileSync(path.join(root,p),'utf8');
const html=get('games/football/index.html');
const scene=get('games/sports/scene.js');
const runtime=get('games/sports/game.js');
const fx=get('games/football/premier-visuals.js');
const ui=get('games/football/premier-ui.js');
const css=get('games/football/premier-ui.css');
const basketball=get('games/basketball/index.html');
for(const file of ['games/football/premier-visuals.js','games/football/premier-ui.js','games/sports/scene.js','games/sports/game.js']){
  new vm.Script(get(file),{filename:file});
}
assert.match(html,/premier-visuals\.js/);
assert.match(html,/premier-ui\.js/);
assert.match(html,/premier-ui\.css/);
assert.match(html,/id="shotPower"/);
assert.match(html,/id="viewCamera"/);
assert.match(html,/id="broadcastScore"/);
assert.match(html,/data-shot-style="curl"/);
assert.match(html,/data-shot-style="power"/);
assert.match(html,/data-aim="left"/);
assert.match(html,/data-aim="right"/);
assert.match(scene,/if\(!basket&&window\.PremierFootball/);
assert.match(scene,/if\(premier\)premier\.frame\(S,dt\)/);
assert.match(scene,/special\.shotPower/);
assert.match(scene,/special\.shotCurve/);
assert.match(runtime,/window\.PremierFootball\?\.shotPower/);
assert.match(runtime,/school-football-question/);
assert.match(runtime,/school-football-result/);
assert.match(runtime,/school-football-outcome/);
assert.match(runtime,/school-football-next/);
assert.doesNotMatch(basketball,/premier-visuals|premier-ui/);
assert.match(css,/\[data-sport="football"\]/);
assert.doesNotMatch(fx,/https?:\/\/|cdn\.|eval\(|new Function\(/);
assert.doesNotMatch(ui,/localStorage|sessionStorage|apiKey|correctAnswer/);
const ctx={window:{}};
vm.runInNewContext(fx,ctx,{timeout:2000});
const director=ctx.window.PremierFootball;
assert.equal(director.cameraMode,'broadcast');
assert.equal(director.nextCamera(),'pitchside');
assert.equal(director.nextCamera(),'goalkeeper');
assert.equal(director.nextCamera(),'broadcast');
assert.equal(director.setCamera('not-a-camera'),'broadcast');
console.log('Premier Football V21: static integration, camera API, offline and school messaging checks passed.');
