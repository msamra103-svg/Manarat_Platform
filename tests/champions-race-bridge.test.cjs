const assert=require('node:assert/strict');
const vm=require('node:vm');
const fs=require('node:fs');
const path=require('node:path');
const src=fs.readFileSync(path.join(__dirname,'../games/champions-race/school-bridge.js'),'utf8');
async function main(){
  const events=[],listeners={};
  const parent={postMessage(obj,origin){events.push({obj,origin});}};
  const cp=()=>({cleared:false,isOpen:false,targetAngle:0,lightMat:{color:{setHex(){}},emissive:{setHex(){}}}});
  const engine={checkpoints:[cp(),cp(),cp()],checkpointTotal:n=>n,openQuestionForCurrentCheckpoint(){throw Error('local question called')},currentCheckpointIndex:0,state:'DRIVING',clock:5,stats:{pauseStartStamp:0,pausedTimeAccum:0,correctCount:0,wrongAttempts:0,points:1000},updateHUD(){this._hud=true},triggerCorrectAnswerCelebration(){this.state='CORRECT_CELEBRATION';this.stats.correctCount++},};
  const UIController={showResultsModal(){throw Error('local results called')},showBanner(s){this._banner=s}};
  const window={parent,addEventListener(k,fn){listeners[k]=fn}};
  const context={window,parent,location:{origin:'https://school.example',search:'?school=1'},URLSearchParams,Number,Object,Math,setTimeout,clearTimeout,console,createDefaultConfig:()=>({carModel:'ferrari_458_real'}),GameEngine:engine,UIController,APP_CONFIG:{checkpointCount:3},document:{documentElement:{style:{setProperty(){}}},getElementById(){return {classList:{add(){}}}}},SoundFX:{playWrongWarning(){} }};
  vm.runInNewContext(src,context);
  const bridge=window.RaceSchoolBridge;
  assert(bridge.enabled);
  const wait=bridge.awaitPlatformConfiguration();
  assert.equal(events.at(-1).obj.type,'school-race-ready');
  assert.equal(events.at(-1).origin,'https://school.example');
  listeners.message({origin:'https://attacker.example',source:parent,data:{type:'school-race-config',token:'attack',count:2}});
  assert.equal(bridge.snapshot().configured,false);
  listeners.message({origin:'https://school.example',source:parent,data:{type:'school-race-config',token:'task:123',count:3,school:'مدرسة أبو عبيدة الإعدادية للبنين'}});
  await wait;
  assert.equal(context.window.__EXPORTED_CONFIG__.questions.length,3);
  assert.equal(context.window.__EXPORTED_CONFIG__.questions[0].correctAnswer,'');
  assert.equal(context.window.__EXPORTED_CONFIG__.schoolName,'مدرسة أبو عبيدة الإعدادية للبنين');
  assert.equal(engine.checkpointTotal(3),3);
  engine.openQuestionForCurrentCheckpoint();
  assert.equal(events.at(-1).obj.type,'school-race-question');
  assert.equal(events.at(-1).obj.index,0);
  assert.equal(engine.state,'QUESTION');
  listeners.message({origin:'https://school.example',source:parent,data:{type:'school-race-continue',token:'wrong-token',index:0,correct:true}});
  assert.equal(engine.state,'QUESTION');
  listeners.message({origin:'https://school.example',source:parent,data:{type:'school-race-continue',token:'task:123',index:99,correct:true}});
  assert.equal(engine.state,'QUESTION');
  listeners.message({origin:'https://school.example',source:parent,data:{type:'school-race-continue',token:'task:123',index:0,correct:false}});
  assert.equal(engine.state,'CORRECT_CELEBRATION');
  assert.equal(engine.stats.wrongAttempts,1);
  assert.equal(engine.stats.correctCount,0);
  assert.equal(engine.checkpoints[0].isOpen,true);
  engine.currentCheckpointIndex=1;engine.state='DRIVING';engine.openQuestionForCurrentCheckpoint();
  listeners.message({origin:'https://school.example',source:parent,data:{type:'school-race-continue',token:'task:123',index:1,correct:true}});
  assert.equal(engine.stats.correctCount,1);
  assert.equal(engine.state,'CORRECT_CELEBRATION');
  engine.currentCheckpointIndex=2;engine.state='DRIVING';engine.openQuestionForCurrentCheckpoint();
  listeners.message({origin:'https://school.example',source:parent,data:{type:'school-race-continue',token:'task:123',index:2,pending:true,correct:false}});
  assert.equal(engine.stats.wrongAttempts,1,'pending answers must not count as wrong');
  assert.equal(engine.stats.correctCount,1,'pending answers must not score a goal');
  assert.equal(engine.checkpoints[2].isOpen,true);
  UIController.showResultsModal();assert(!events.some(x=>x.obj.type==='school-race-finished'));
  engine.currentCheckpointIndex=3;UIController.showResultsModal();assert.equal(events.at(-1).obj.type,'school-race-finished');
  UIController.showResultsModal();assert.equal(events.filter(x=>x.obj.type==='school-race-finished').length,1);
  console.log('PASS: handshake, student questions do not contain answers, token/origin validation, wrong/correct flow, finish guard');
}
main().catch(e=>{console.error(e);process.exit(1)});
