// نحت تشريحي لحصان سباق أصيل في وضع الربط، فوق نفس الهيكل العظمي المستخدم في اللعبة.
// +X للأمام، +Y للأعلى، +Z لليمين (متناظر: نعرّف الجهة اليمنى فقط). كل كتلة = عظم أو عضلة.
import { Sculpt, ellipsoid as E, roundCone as RC, tube, smax } from './sdf.mjs';
import { LEGS } from '../../src/horse/horseAnatomy.js';

export const HEAD_FEATURES = {
  eye: [1.452, 2.062, 0.083], eyeR: 0.021,
  ear: [1.30, 2.215, 0.058],
  nostril: [1.785, 1.842, 0.036],
};

export function buildHorseSculpt() {
  const S = new Sculpt({ mirrorZ: true });
  const F = LEGS.FR.joints, H = LEGS.HR.joints;
  const fz = LEGS.FR.z, hz = LEGS.HR.z;
  const j3 = (j, z) => [j[0], j[1], z];

  // ---------------- الجذع ----------------
  S.add(E([0.02, 1.30, 0], [0.62, 0.30, 0.265]), 0);                        // القفص الصدري (البرميل)
  S.add(E([0.40, 1.27, 0], [0.30, 0.335, 0.235], { z: 0.12 }), 0.12);       // صدر عميق عند الحزام
  S.add(E([0.64, 1.25, 0], [0.15, 0.21, 0.19], { z: 0.3 }), 0.09);          // مقدّم الصدر
  S.add(E([0.66, 1.19, 0.085], [0.09, 0.10, 0.075]), 0.05);                 // عضلتا الصدر
  S.add(E([-0.24, 1.25, 0], [0.42, 0.245, 0.255]), 0.14);                   // البطن يرتفع نحو الخاصرة
  S.add(E([0.36, 1.555, 0], [0.20, 0.085, 0.065], { z: -0.12 }), 0.07);     // الحارك البارز
  S.add(E([-0.10, 1.50, 0], [0.34, 0.09, 0.14]), 0.10);                     // الظهر
  S.add(E([-0.56, 1.44, 0], [0.34, 0.215, 0.235]), 0.13);                   // القطن والكفل
  S.add(E([-0.80, 1.36, 0], [0.19, 0.25, 0.215]), 0.10);                    // مؤخر الكفل المستدير
  S.add(E([-0.47, 1.555, 0.17], [0.065, 0.045, 0.045]), 0.06);              // نتوء الورك
  S.add(E([-0.93, 1.47, 0], [0.055, 0.06, 0.05]), 0.05);                    // قاعدة الذيل

  // ---------------- الكتف والرجل الأمامية ----------------
  S.add(E([0.50, 1.37, 0.165], [0.105, 0.27, 0.065], { z: 0.5 }), 0.07);    // لوح الكتف المائل
  S.add(E([0.60, 1.21, 0.15], [0.09, 0.10, 0.075]), 0.06);                  // رأس الكتف
  S.add(E([0.41, 1.12, 0.165], [0.10, 0.145, 0.07], { z: -0.3 }), 0.06);    // ثلاثية الرؤوس
  S.add(RC(j3(F[0], fz + 0.015), j3(F[1], fz), 0.09, 0.062), 0.06);         // العضد
  S.add(RC(j3(F[1], fz), j3(F[2], fz), 0.062, 0.036), 0.035);               // الساعد
  S.add(E([0.425, 0.82, fz], [0.058, 0.125, 0.05], { z: 0.06 }), 0.045);    // عضلات الساعد
  S.add(E([F[2][0], F[2][1], fz], [0.042, 0.052, 0.042]), 0.025);           // الركبة
  S.add(RC([F[2][0], F[2][1] - 0.03, fz], j3(F[3], fz), 0.028, 0.026, 0.9), 0.02); // عظم المدفع
  S.add(RC([F[2][0] - 0.022, F[2][1] - 0.06, fz], [F[3][0] - 0.024, F[3][1] + 0.03, fz], 0.016, 0.018), 0.018); // الأوتار الخلفية
  S.add(E([F[3][0] - 0.004, F[3][1], fz], [0.036, 0.04, 0.034]), 0.02);     // الرمانة
  S.add(RC([F[3][0], F[3][1] - 0.01, fz], [F[4][0] - 0.012, 0.085, fz], 0.03, 0.036), 0.02); // الرسغ المائل
  hoof(S, F[4][0], fz);

  // ---------------- الفخذ والرجل الخلفية ----------------
  S.add(E([-0.60, 1.43, 0.16], [0.22, 0.155, 0.10], { z: -0.2 }), 0.08);    // الألوية
  S.add(E([-0.66, 1.15, 0.15], [0.15, 0.27, 0.10], { z: 0.42 }), 0.08);     // خلف الفخذ (أوتار المأبض)
  S.add(E([-0.47, 1.13, 0.155], [0.085, 0.19, 0.08], { z: 0.44 }), 0.07);   // رباعية الرؤوس
  S.add(RC(j3(H[0], hz), j3(H[1], hz + 0.005), 0.105, 0.068), 0.07);        // عظم الفخذ
  S.add(E([-0.38, 1.03, 0.12], [0.07, 0.08, 0.075]), 0.07);                 // ثنية الخاصرة
  S.add(RC(j3(H[1], hz), j3(H[2], hz), 0.064, 0.038), 0.04);                // الساق
  S.add(E([-0.575, 0.84, hz], [0.06, 0.135, 0.05], { z: -0.62 }), 0.05);    // عضلة الساق
  S.add(RC([-0.63, 0.83, hz], [-0.775, 0.655, hz], 0.022, 0.02), 0.03);     // وتر العرقوب
  S.add(E([H[2][0], H[2][1], hz], [0.046, 0.055, 0.04]), 0.028);            // العرقوب
  S.add(E([H[2][0] - 0.055, H[2][1] + 0.05, hz], [0.026, 0.03, 0.026]), 0.02); // رأس العرقوب
  S.add(RC([H[2][0], H[2][1] - 0.03, hz], j3(H[3], hz), 0.03, 0.027, 0.9), 0.02);
  S.add(RC([H[2][0] - 0.026, H[2][1] - 0.07, hz], [H[3][0] - 0.024, H[3][1] + 0.03, hz], 0.016, 0.018), 0.018);
  S.add(E([H[3][0] - 0.004, H[3][1], hz], [0.036, 0.04, 0.034]), 0.02);
  S.add(RC([H[3][0], H[3][1] - 0.01, hz], [H[4][0] - 0.012, 0.085, hz], 0.03, 0.036), 0.02);
  hoof(S, H[4][0], hz);

  // ---------------- الرقبة ----------------
  // رقبة مقوّسة عضلية مضغوطة جانبيًا: عريضة عند الكتف ونحيلة عند الحلق
  S.add(tube([[0.46, 1.40, 0, 0.26], [0.70, 1.49, 0, 0.215], [0.87, 1.67, 0, 0.172], [1.02, 1.855, 0, 0.138], [1.16, 2.01, 0, 0.11], [1.27, 2.11, 0, 0.095]], 0.06, 0.6), 0.09);
  S.add(tube([[0.56, 1.63, 0, 0.07], [0.80, 1.80, 0, 0.062], [1.0, 1.99, 0, 0.055], [1.18, 2.14, 0, 0.05]], 0.05, 0.75), 0.06); // قوس العُرف
  S.add(tube([[0.70, 1.33, 0, 0.1], [0.90, 1.53, 0, 0.082], [1.08, 1.76, 0, 0.064], [1.24, 1.97, 0, 0.05]], 0.05, 0.8), 0.06); // الحلق

  // ---------------- الرأس ----------------
  // رأس طويل جاف: جبهة عريضة، خد (فك) كبير مستدير، وجه مستقيم يضيق نحو خطم بمنخرين واسعين
  const tilt = -0.62;
  S.add(E([1.36, 2.12, 0], [0.125, 0.098, 0.092], { z: tilt }), 0.05);      // الجمجمة
  S.add(E([1.41, 2.105, 0], [0.09, 0.05, 0.085], { z: tilt }), 0.03);       // الجبهة العريضة
  S.add(E([1.44, 2.085, 0.062], [0.045, 0.02, 0.036], { z: tilt }), 0.015);  // قوس الحاجب
  S.add(RC([1.42, 2.075, 0], [1.72, 1.865, 0], 0.082, 0.052, 0.8), 0.045);  // الوجه (عظم الأنف)
  S.add(E([1.42, 1.985, 0.048], [0.115, 0.092, 0.04], { z: tilt }), 0.035); // الخد العريض (عضلة الماضغ)
  S.add(E([1.53, 2.0, 0.066], [0.1, 0.014, 0.014], { z: tilt }), 0.012);    // عرف الوجنة
  S.add(RC([1.40, 1.955, 0.04], [1.70, 1.80, 0.022], 0.04, 0.027), 0.03);   // الفك السفلي
  S.add(RC([1.50, 1.99, 0], [1.72, 1.83, 0], 0.062, 0.045, 0.75), 0.04);    // ما بين الفكين
  S.add(E([1.755, 1.825, 0], [0.064, 0.056, 0.054], { z: tilt }), 0.035);   // الخطم
  S.add(E([HEAD_FEATURES.nostril[0], HEAD_FEATURES.nostril[1], HEAD_FEATURES.nostril[2]], [0.024, 0.02, 0.016], { z: tilt }), 0.01, 'nose'); // حافة المنخر
  S.add(E([1.795, 1.795, 0], [0.036, 0.03, 0.042], { z: tilt }), 0.02, 'lips'); // الشفة العليا
  S.add(E([1.745, 1.772, 0], [0.045, 0.026, 0.036], { z: tilt }), 0.02, 'lips'); // الشفة السفلى والذقن
  S.sub(E([HEAD_FEATURES.nostril[0] + 0.006, HEAD_FEATURES.nostril[1] - 0.002, HEAD_FEATURES.nostril[2] + 0.008], [0.013, 0.011, 0.012], { z: tilt }), 0.006); // فتحة المنخر
  S.sub(E(HEAD_FEATURES.eye, [0.03, 0.024, 0.03], { z: tilt }), 0.01);       // تجويف العين
  S.add(E([HEAD_FEATURES.eye[0] + 0.004, HEAD_FEATURES.eye[1] + 0.019, HEAD_FEATURES.eye[2] - 0.003], [0.032, 0.012, 0.024], { z: tilt * 0.6 }), 0.008); // الجفن العلوي
  S.add(E([HEAD_FEATURES.eye[0] + 0.002, HEAD_FEATURES.eye[1] - 0.02, HEAD_FEATURES.eye[2] - 0.005], [0.027, 0.009, 0.02], { z: tilt * 0.6 }), 0.007); // الجفن السفلي

  // عضلات تظهر تحت الجلد: خط بين الكتف والصدر، وتموّج خفيف للأضلاع الخلفية
  S.displace((x, y, z, d) => {
    if (d > 0.03 || d < -0.03 || z < 0.12 || x < -0.32 || x > 0.2 || y < 1.08 || y > 1.5) return 0;
    const mx = Math.sin(((x + 0.32) / 0.52) * Math.PI), my = Math.sin(((y - 1.08) / 0.42) * Math.PI);
    return 0.0013 * Math.sin(x * (2 * Math.PI / 0.1) - y * 2.4) * mx * my;
  });

  const base = S.d.bind(S);
  const f = (x, y, z) => smax(base(x, y, z), -y, 0.004);
  return { S, f };
}

// الحافر: مخروط مقطوع بجدار أمامي مستقيم مائل (≈57° عن الأرض كحافر سليم)، نعل مستوٍ،
// حافة تاج واضحة، وكعبان صغيران مستديران في الخلف.
function hoof(S, x, z) {
  S.add(RC([x - 0.008, 0.094, z], [x + 0.034, -0.03, z], 0.04, 0.066), 0.007, 'hoof');
  S.add(E([x - 0.05, 0.04, z + 0.018], [0.026, 0.03, 0.022]), 0.012, 'hoof'); // الكعب الخارجي
  S.add(E([x - 0.05, 0.04, z - 0.018], [0.026, 0.03, 0.022]), 0.012, 'hoof'); // الكعب الداخلي
  S.add(RC([x - 0.012, 0.1, z], [x - 0.004, 0.088, z], 0.043, 0.044), 0.012);  // شريط التاج (جلد بشعر فوق الحافر)
}
