import { Sculpt, ellipsoid as E, roundCone as RC, tube, roundBox, smax } from "./sdf.mjs";
import { LEGS, SPINE_JOINTS } from "../../src/camel/camelAnatomy.mjs";
const HEAD_FEATURES = {
  eye: [1.976, 1.884, 0.086],
  eyeR: 0.0205,
  ear: [1.84, 1.968, 0.064],
  nostril: [2.356, 1.735, 0.033]
};
function buildCamelSculpt() {
  const S = new Sculpt({ mirrorZ: true });
  const FL = LEGS.FR.joints, HL = LEGS.HR.joints;
  const fz = LEGS.FR.z, hz = LEGS.HR.z;
  const j3 = (j, z) => [j[0], j[1], z];
  S.add(E([0.06, 1.44, 0], [0.6, 0.33, 0.285]), 0);
  S.add(E([0.36, 1.34, 0], [0.3, 0.34, 0.245], { z: 0.2 }), 0.12);
  S.add(E([0.55, 1.33, 0], [0.17, 0.25, 0.165], { z: 0.35 }), 0.1);
  S.add(E([0.36, 1.035, 0], [0.165, 0.07, 0.115]), 0.09);
  S.add(E([0.36, 1, 0], [0.12, 0.035, 0.09]), 0.04, "callus");
  S.add(E([-0.22, 1.405, 0], [0.42, 0.265, 0.275]), 0.14);
  S.add(E([-0.58, 1.5, 0], [0.33, 0.215, 0.215]), 0.14);
  S.add(E([-0.79, 1.5, 0], [0.19, 0.2, 0.19]), 0.1);
  S.add(E([-0.45, 1.615, 0.175], [0.07, 0.055, 0.05]), 0.06);
  S.add(E([-0.865, 1.43, 0.1], [0.09, 0.11, 0.08]), 0.07);
  S.add(E([-0.92, 1.48, 0], [0.05, 0.06, 0.045]), 0.05);
  S.add(E([-0.03, 1.73, 0], [0.42, 0.26, 0.2], { z: -0.1 }), 0.2);
  S.add(E([0, 1.86, 0], [0.25, 0.155, 0.13], { z: -0.08 }), 0.12);
  S.add(E([0.41, 1.6, 0], [0.19, 0.13, 0.14]), 0.12);
  S.add(E([0.465, 1.47, 0.19], [0.1, 0.24, 0.07], { z: 0.32 }), 0.07);
  S.add(E([0.41, 1.19, 0.175], [0.095, 0.15, 0.075], { z: -0.25 }), 0.07);
  S.add(RC(j3(FL[0], fz + 0.02), j3(FL[1], fz), 0.095, 0.062), 0.06);
  S.add(E([FL[1][0] - 0.035, FL[1][1], fz - 5e-3], [0.042, 0.048, 0.038]), 0.03, "callus");
  S.add(RC(j3(FL[1], fz), j3(FL[2], fz), 0.06, 0.04), 0.04);
  S.add(E([0.43, 0.88, fz], [0.062, 0.15, 0.052], { z: 0.23 }), 0.05);
  S.add(E([FL[2][0], FL[2][1], fz], [0.048, 0.06, 0.045]), 0.03);
  S.add(E([FL[2][0] + 0.036, FL[2][1], fz], [0.024, 0.042, 0.034]), 0.015, "callus");
  S.add(RC([FL[2][0], FL[2][1] - 0.02, fz], j3(FL[3], fz), 0.033, 0.03, 0.85), 0.03);
  S.add(RC([FL[2][0] - 0.022, FL[2][1] - 0.05, fz], [FL[3][0] - 0.022, FL[3][1] + 0.05, fz], 0.019, 0.021), 0.02);
  S.add(E([FL[3][0], FL[3][1], fz], [0.045, 0.05, 0.042]), 0.025);
  S.add(RC([FL[3][0], FL[3][1] - 0.01, fz], [FL[4][0] + 0.03, 0.06, fz], 0.038, 0.05), 0.03);
  footPad(S, FL[4][0], fz, 1);
  S.add(E([-0.62, 1.47, 0.165], [0.22, 0.14, 0.09], { z: -0.15 }), 0.08);
  S.add(E([-0.62, 1.2, 0.16], [0.125, 0.26, 0.09], { z: 0.6 }), 0.08);
  S.add(E([-0.445, 1.19, 0.16], [0.07, 0.18, 0.07], { z: 0.44 }), 0.06);
  S.add(RC(j3(HL[0], hz), j3(HL[1], hz + 0.01), 0.1, 0.058), 0.07);
  S.add(E([HL[1][0] + 0.02, HL[1][1] - 0.02, hz + 0.012], [0.04, 0.045, 0.038]), 0.03, "callus");
  S.add(E([-0.36, 1.22, 0.1], [0.06, 0.07, 0.07]), 0.05);
  S.add(RC(j3(HL[1], hz), j3(HL[2], hz), 0.058, 0.038), 0.04);
  S.add(E([-0.52, 0.87, hz], [0.058, 0.15, 0.048], { z: -0.54 }), 0.05);
  S.add(RC([-0.56, 0.86, hz], [-0.69, 0.635, hz], 0.024, 0.021), 0.03);
  S.add(E([HL[2][0], HL[2][1], hz], [0.05, 0.055, 0.04]), 0.03);
  S.add(E([HL[2][0] - 0.06, HL[2][1] + 0.04, hz], [0.03, 0.03, 0.03]), 0.02);
  S.add(RC([HL[2][0], HL[2][1] - 0.02, hz], j3(HL[3], hz), 0.033, 0.03, 0.85), 0.03);
  S.add(RC([HL[2][0] - 0.024, HL[2][1] - 0.06, hz], [HL[3][0] - 0.022, HL[3][1] + 0.05, hz], 0.018, 0.02), 0.02);
  S.add(E([HL[3][0], HL[3][1], hz], [0.044, 0.048, 0.04]), 0.025);
  S.add(RC([HL[3][0], HL[3][1] - 0.01, hz], [HL[4][0] + 0.028, 0.058, hz], 0.036, 0.047), 0.03);
  footPad(S, HL[4][0], hz, 0.92);
  S.add(tube([[0.6, 1.43, 0, 0.27], [0.82, 1.39, 0, 0.215], [1.1, 1.375, 0, 0.14], [1.38, 1.465, 0, 0.112], [1.62, 1.645, 0, 0.096], [1.8, 1.835, 0, 0.09]], 0.06, 0.7), 0.08);
  S.add(tube([[0.74, 1.235, 0, 0.115], [1.05, 1.28, 0, 0.078], [1.4, 1.385, 0, 0.058], [1.7, 1.62, 0, 0.05]], 0.06, 0.8), 0.07);
  S.add(tube([[0.64, 1.63, 0, 0.075], [0.95, 1.505, 0, 0.058], [1.35, 1.555, 0, 0.05], [1.7, 1.8, 0, 0.046]], 0.05, 0.8), 0.06);
  S.add(E([0.66, 1.27, 0.12], [0.12, 0.12, 0.06], { z: 0.5 }), 0.07);
  const tilt = -0.3;
  S.add(E([1.895, 1.91, 0], [0.13, 0.11, 0.1], { z: tilt }), 0.06);
  S.add(E([1.82, 1.928, 0], [0.072, 0.07, 0.07]), 0.04);
  S.add(E([1.975, 1.922, 0.068], [0.05, 0.022, 0.04], { z: tilt }), 0.02);
  S.add(E([1.99, 1.842, 0.068], [0.09, 0.044, 0.032], { z: tilt }), 0.03);
  S.add(E([1.91, 1.782, 0.056], [0.088, 0.072, 0.04], { z: -0.2 }), 0.04);
  S.add(RC([1.98, 1.895, 0], [2.26, 1.772, 0], 0.08, 0.056, 0.78), 0.05);
  S.add(E([2.11, 1.85, 0], [0.11, 0.03, 0.04], { z: -0.38 }), 0.03);
  S.add(E([2.3, 1.73, 0], [0.068, 0.06, 0.052], { z: tilt }), 0.04);
  S.add(E([2.36, 1.684, 0.02], [0.05, 0.044, 0.033], { z: -0.55 }), 0.022, "lips");
  S.add(E([2.29, 1.64, 0], [0.068, 0.03, 0.04], { z: -0.12 }), 0.022, "lips");
  S.add(RC([1.9, 1.762, 0.048], [2.25, 1.654, 0.026], 0.032, 0.027), 0.03);
  S.add(RC([1.94, 1.82, 0], [2.27, 1.69, 0], 0.075, 0.05, 0.72), 0.05);
  S.add(E([2.25, 1.634, 0], [0.046, 0.028, 0.036]), 0.02);
  S.sub(roundBox([2.404, 1.674, 0], [0.04, 0.042, 35e-4], 0, { z: -0.5 }), 6e-3);
  S.sub(E(HEAD_FEATURES.eye, [0.03, 0.025, 0.03], { z: tilt }), 0.01);
  S.add(E([HEAD_FEATURES.eye[0] + 4e-3, HEAD_FEATURES.eye[1] + 0.02, HEAD_FEATURES.eye[2] - 2e-3], [0.033, 0.013, 0.024], { z: -0.25 }), 8e-3);
  S.add(E([HEAD_FEATURES.eye[0] + 2e-3, HEAD_FEATURES.eye[1] - 0.02, HEAD_FEATURES.eye[2] - 4e-3], [0.028, 9e-3, 0.02], { z: -0.3 }), 7e-3);
  S.add(E([HEAD_FEATURES.nostril[0], HEAD_FEATURES.nostril[1], HEAD_FEATURES.nostril[2]], [0.022, 6e-3, 6e-3], { z: -0.7, y: -0.4 }), 4e-3, "nose");
  S.displace((x, y, z, d) => {
    if (d > 0.03 || d < -0.03 || z < 0.12 || x < -0.2 || x > 0.42 || y < 1.18 || y > 1.62) return 0;
    const mx = Math.sin((x + 0.2) / 0.62 * Math.PI);
    const my = Math.sin((y - 1.18) / 0.44 * Math.PI);
    return 2e-3 * Math.sin((x - 0.02) * (2 * Math.PI / 0.095) - y * 2) * mx * my;
  });
  const base = S.d.bind(S);
  const f = (x, y, z) => smax(base(x, y, z), -y, 6e-3);
  return { S, f, spine: SPINE_JOINTS };
}
function footPad(S, x, z, s) {
  S.add(E([x + 0.02 * s, 0.042, z], [0.088 * s, 0.046, 0.08 * s]), 0.035);
  S.add(E([x - 0.03 * s, 0.05, z], [0.05 * s, 0.04, 0.06 * s]), 0.03);
  for (const dz of [-0.033, 0.033]) {
    S.add(E([x + 0.075 * s, 0.036, z + dz * s], [0.045 * s, 0.032, 0.034 * s]), 0.022);
    S.add(E([x + 0.115 * s, 0.03, z + dz * s * 1.08], [0.018, 0.015, 0.016]), 8e-3, "nail");
  }
  S.sub(roundBox([x + 0.115 * s, 0.035, z], [0.045, 0.04, 4e-3]), 6e-3);
}
export {
  HEAD_FEATURES,
  buildCamelSculpt
};
